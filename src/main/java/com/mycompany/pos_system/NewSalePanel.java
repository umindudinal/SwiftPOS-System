    private void btnAddToCartActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddToCartActionPerformed
        // TODO add your handling code here:
        try {
            // 1. Check whether a row has been selected in the table.
            int row = tblSaleProducts.getSelectedRow();
            if (row == -1) {
                javax.swing.JOptionPane.showMessageDialog(null, "Please select a product first!");
                return;
            }

            // 2. Retrieve the details of the selected row.
            String id = tblSaleProducts.getValueAt(row, 0).toString();
            String name = tblSaleProducts.getValueAt(row, 1).toString();
            double price = Double.parseDouble(tblSaleProducts.getValueAt(row, 2).toString());
            int stock = Integer.parseInt(tblSaleProducts.getValueAt(row, 3).toString());

            // 3. Ask for the quantity to be purchased.
            String qtyStr = javax.swing.JOptionPane.showInputDialog(null, "Enter Quantity:", "1");

            // Stop the process if the user clicks 'Cancel' or leaves the input empty.
            if (qtyStr == null || qtyStr.trim().isEmpty()) {
                return;
            }

            int qty = Integer.parseInt(qtyStr);

            // 4. Display an error message if the requested quantity exceeds the available stock.
            if (qty > stock) {
                javax.swing.JOptionPane.showMessageDialog(null, "Not enough stock! Available: " + stock);
                return;
            }
            if (qty <= 0) {
                javax.swing.JOptionPane.showMessageDialog(null, "Quantity must be greater than 0!");
                return;
            }

            // 5. Calculate the total and add the item to the Cart Table.
            double total = price * qty;

            javax.swing.table.DefaultTableModel cartModel = (javax.swing.table.DefaultTableModel) tblCart.getModel();
            cartModel.addRow(new Object[]{
                id,
                name,
                price,
                qty,
                total
            });

            // 6. Update the grand total.
            calculateTotal();

        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(null, "Invalid quantity entered! Please enter a number.");
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(null, e);
        }
    }//GEN-LAST:event_btnAddToCartActionPerformed

