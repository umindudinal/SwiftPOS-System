    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        try {
            if (tblCart.getRowCount() == 0) {
                javax.swing.JOptionPane.showMessageDialog(null, "Cart is empty! Please add products first.");
                return;
            }

            double total = Double.parseDouble(lblTotal.getText());

            String cashStr = javax.swing.JOptionPane.showInputDialog(null,
                "Total Amount: Rs. " + lblTotal.getText() + "\n\nEnter Customer Payment:", "Payment", javax.swing.JOptionPane.PLAIN_MESSAGE);

            if (cashStr == null || cashStr.trim().isEmpty()) {
                return;
            }

            double pay = Double.parseDouble(cashStr);

            if (pay < total) {
                javax.swing.JOptionPane.showMessageDialog(null, "Insufficient Amount! Please enter a valid amount.");
                return;
            }

            double balance = pay - total;

            java.sql.Connection conn = DBConnect.connect();

            // --- 1. බිලේ ප්‍රධාන විස්තර Sales Table එකට සේව් කිරීම ---
            // (RETURN_GENERATED_KEYS පාවිච්චි කරන්නේ අලුතෙන් හැදෙන sale_id එක ගන්නයි)
            String insertSale = "INSERT INTO sales (subtotal, discount, net_total, paid_amount, balance, payment_method) VALUES (?, ?, ?, ?, ?, ?)";
            java.sql.PreparedStatement pstSale = conn.prepareStatement(insertSale, java.sql.Statement.RETURN_GENERATED_KEYS);
            pstSale.setString(1, txtSubtotal.getText());
            pstSale.setString(2, txtDiscount.getText().isEmpty() ? "0.00" : txtDiscount.getText());
            pstSale.setString(3, String.valueOf(total));
            pstSale.setString(4, String.valueOf(pay));
            pstSale.setString(5, String.valueOf(balance));
            pstSale.setString(6, "Cash");
            pstSale.executeUpdate();

            // අලුතෙන් හැදුන බිල් අංකය (sale_id) හොයාගැනීම
            java.sql.ResultSet rsKeys = pstSale.getGeneratedKeys();
            int lastSaleId = 0;
            if(rsKeys.next()) {
                lastSaleId = rsKeys.getInt(1);
            }

            // --- 2. Stock අඩු කිරීම සහ sale_items table එකට බඩු විස්තර යැවීම ---
            for (int i = 0; i < tblCart.getRowCount(); i++) {
                String productId = tblCart.getValueAt(i, 0).toString();
                String name = tblCart.getValueAt(i, 1).toString();
                String price = tblCart.getValueAt(i, 2).toString();
                String qtySold = tblCart.getValueAt(i, 3).toString();
                String itemTotal = tblCart.getValueAt(i, 4).toString();

                // 2.1 Stock එක අඩු කිරීම
                String updateStock = "UPDATE products SET quantity = quantity - ? WHERE barcode = ?";
                java.sql.PreparedStatement pstStock = conn.prepareStatement(updateStock);
                pstStock.setInt(1, Integer.parseInt(qtySold));
                pstStock.setString(2, productId);
                pstStock.executeUpdate();

                // 2.2 අලුත් sale_items Table එකට විස්තර යැවීම
                String insertItem = "INSERT INTO sale_items (sale_id, product_name, qty, price, total) VALUES (?, ?, ?, ?, ?)";
                java.sql.PreparedStatement pstItem = conn.prepareStatement(insertItem);
                pstItem.setInt(1, lastSaleId);
                pstItem.setString(2, name);
                pstItem.setString(3, qtySold);
                pstItem.setString(4, price);
                pstItem.setString(5, itemTotal);
                pstItem.executeUpdate();
            }

            conn.close();

            // --- 3. බිල් එක (Receipt) Design කිරීම සහ Print කිරීම ---
            StringBuilder bill = new StringBuilder();
            bill.append("==========================================\n");
            bill.append("             MY SUPERMARKET               \n");
            bill.append("        123 Main Street, Colombo 01       \n");
            bill.append("             Tel: 011-2345678             \n");
            bill.append("==========================================\n");
            String invoiceNo = "INV-" + lastSaleId;
            bill.append(String.format("Invoice No: %-15s \n", invoiceNo));
            java.text.SimpleDateFormat sdf = new java.text.SimpleDateFormat("yyyy-MM-dd HH:mm:ss");
            String dateTime = sdf.format(new java.util.Date());
            bill.append(String.format("Date & Time: %-15s \n", dateTime));
            bill.append(String.format("Pay Method: %-15s \n", "Cash"));
            bill.append("------------------------------------------\n");
            bill.append(String.format("%-15s %-5s %-8s %-8s\n", "Item Name", "Qty", "Price", "Total"));
            bill.append("------------------------------------------\n");

            for (int i = 0; i < tblCart.getRowCount(); i++) {
                String name = tblCart.getValueAt(i, 1).toString();
                String qty = tblCart.getValueAt(i, 3).toString();
                String price = tblCart.getValueAt(i, 2).toString();
                String tot = tblCart.getValueAt(i, 4).toString();

                if(name.length() > 14) { name = name.substring(0, 14) + "."; }
                bill.append(String.format("%-15s %-5s %-8s %-8s\n", name, qty, price, tot));
            }

            bill.append("------------------------------------------\n");
            bill.append(String.format("%-28s %12s\n", "Subtotal:", txtSubtotal.getText()));

            String discount = txtDiscount.getText().isEmpty() ? "0.00" : txtDiscount.getText();
            bill.append(String.format("%-28s %12s\n", "Discount:", discount));

            bill.append(String.format("%-28s %12s\n", "Total Amount:", String.format("%.2f", total)));
            bill.append(String.format("%-28s %12s\n", "Cash Paid:", String.format("%.2f", pay)));
            bill.append(String.format("%-28s %12s\n", "Balance:", String.format("%.2f", balance)));
            bill.append("==========================================\n");
            bill.append("          Thank You, Come Again!          \n");
            bill.append("==========================================\n");

            javax.swing.JTextArea billArea = new javax.swing.JTextArea(bill.toString());
            billArea.setFont(new java.awt.Font("Monospaced", java.awt.Font.PLAIN, 14));
            billArea.setEditable(false);

            int printConfirm = javax.swing.JOptionPane.showConfirmDialog(null, new javax.swing.JScrollPane(billArea), "Print Receipt", javax.swing.JOptionPane.YES_NO_OPTION);
            if (printConfirm == javax.swing.JOptionPane.YES_OPTION) {
                billArea.print();
            }

            // --- 4. ඊළඟ බිලට ලෑස්ති වෙන්න ඔක්කොම Clear කරනවා ---
            javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) tblCart.getModel();
            model.setRowCount(0);
            txtSubtotal.setText("");
            txtDiscount.setText("");
            lblTotal.setText("0.00");

            loadProducts();

        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(null, "Invalid amount entered! Please enter numbers only.");
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(null, e);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

