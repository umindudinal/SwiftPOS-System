    public void loadProducts() {
        try {
            java.sql.Connection conn = DBConnect.connect();
            java.sql.Statement st = conn.createStatement();
            java.sql.ResultSet rs = st.executeQuery("SELECT * FROM products");

            // Clear the existing data from the table.
            javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) tblSaleProducts.getModel();
            model.setRowCount(0); 

            // Add the data to the table row by row.
            while(rs.next()) {
                model.addRow(new Object[]{
                    rs.getString("barcode"),       // Product ID
                    rs.getString("product_name"),  // Name
                    rs.getString("price"),         // Price
                    rs.getString("quantity")       // Stock
                });
            }
            conn.close();
        } catch(Exception e) {
            javax.swing.JOptionPane.showMessageDialog(null, e);
        }
    }
    
    public void calculateTotal() {
        try {
            double subtotal = 0;

            // 1. Calculate the subtotal by adding all the items in the table.
            for (int i = 0; i < tblCart.getRowCount(); i++) {
                if (tblCart.getValueAt(i, 4) != null && !tblCart.getValueAt(i, 4).toString().isEmpty()) {
                    subtotal = subtotal + Double.parseDouble(tblCart.getValueAt(i, 4).toString());
                }
            }

            // Display the amount in the Subtotal field.
            txtSubtotal.setText(String.format("%.2f", subtotal));

            // 2. Check the discount amount (if nothing is entered, set it to 0).
            double discount = 0;
            if (!txtDiscount.getText().isEmpty()) {
                discount = Double.parseDouble(txtDiscount.getText());
            }

            // 3. Subtract the discount from the subtotal to calculate the final total.
            double finalTotal = subtotal - discount;

            // Display the final amount in the Total field.
            lblTotal.setText(String.format("%.2f", finalTotal));

        } catch (NumberFormatException e) {
            // Add this to prevent errors when invalid input, such as letters, is entered.
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(null, e);
        }
    }
    

