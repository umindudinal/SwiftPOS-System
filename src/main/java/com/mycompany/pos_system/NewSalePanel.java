    private void btnRemoveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRemoveActionPerformed
        // TODO add your handling code here:
        try {
            javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) tblCart.getModel();

            // Check whether a row has been selected in the table.
            int row = tblCart.getSelectedRow();

            if (row == -1) {
                javax.swing.JOptionPane.showMessageDialog(null, "Please select an item to remove!");
                return;
            }

            // Delete the selected row.
            model.removeRow(row);

            // Recalculate the total after deleting a row.
            calculateTotal();

        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(null, e);
        }
    }//GEN-LAST:event_btnRemoveActionPerformed


