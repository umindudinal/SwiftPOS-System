    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        
        try {
            // 1. Check if any field is empty
            if (txtId.getText().isEmpty() || txtName.getText().isEmpty() || txtPrice.getText().isEmpty() || txtStock.getText().isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(null, "Please fill in all fields!");
                return; // Code එක එතනින්ම නවත්වනවා
            }

            // 2. Number Validation: Check if Price and Stock are valid numbers
            try {
                Double.parseDouble(txtPrice.getText()); // Price එකට දශම සංඛ්‍යා (Decimals) පුළුවන්
                Integer.parseInt(txtStock.getText());   // Stock එකට පූර්ණ සංඛ්‍යා (Integers) පමණයි
            } catch (NumberFormatException e) {
                // අකුරු ගහලා තිබ්බොත් මේ Message එක එනවා
                javax.swing.JOptionPane.showMessageDialog(null, "Please enter valid numbers for Price and Stock!");
                return; // Database එකට යන එක නවත්වනවා
            }

            // 3. Database Connection and Save Data
            java.sql.Connection conn = DBConnect.connect();
            String sql = "INSERT INTO products (barcode, product_name, category, price, quantity) VALUES (?, ?, ?, ?, ?)";

            java.sql.PreparedStatement pst = conn.prepareStatement(sql);
            pst.setString(1, txtId.getText());
            pst.setString(2, txtName.getText());
            pst.setString(3, cmbCategory.getSelectedItem().toString());
            pst.setString(4, txtPrice.getText());
            pst.setString(5, txtStock.getText());

            pst.executeUpdate(); 

            javax.swing.JOptionPane.showMessageDialog(null, "Product Saved Successfully!");

            // Clear the fields
            txtId.setText("");
            txtName.setText("");
            cmbCategory.setSelectedIndex(0);
            txtPrice.setText("");
            txtStock.setText("");

            // Refresh the table
            loadProductTable();
            autoId();

            conn.close();

        } catch(Exception e) {
            javax.swing.JOptionPane.showMessageDialog(null, e);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

