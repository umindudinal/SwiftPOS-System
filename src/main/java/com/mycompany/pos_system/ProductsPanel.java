    public void loadProductTable() {
        try {
            java.sql.Connection conn = DBConnect.connect();
            java.sql.Statement st = conn.createStatement();
            java.sql.ResultSet rs = st.executeQuery("SELECT * FROM products");

            // Table එකේ දැනට තියෙන දත්ත මකා ගැනීම (Clear කිරීම)
            javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) tblProducts.getModel();
            model.setRowCount(0); 

            // Database එකෙන් එන දත්ත පේළියෙන් පේළිය Table එකට දැමීම
            while(rs.next()) {
                model.addRow(new Object[]{
                    rs.getString("barcode"),       // අර අපි Product ID එකට පාවිච්චි කරන column එක
                    rs.getString("product_name"),
                    rs.getString("category"),
                    rs.getString("price"),
                    rs.getString("quantity")
                });
            }
            conn.close();
        } catch(Exception e) {
            javax.swing.JOptionPane.showMessageDialog(null, e);
        }
    }
    
    public void autoId() {
        try {
            java.sql.Connection conn = DBConnect.connect();
            java.sql.Statement st = conn.createStatement();

            // F අකුරෙන් පටන් ගන්න ලොකුම ID එක (Barcode එක) හොයාගන්නවා
            java.sql.ResultSet rs = st.executeQuery("SELECT MAX(barcode) FROM products WHERE barcode LIKE 'F%'");

            if (rs.next() && rs.getString(1) != null) {
                String lastId = rs.getString(1); // උදාහරණයක් විදියට "F1050" ගනීවි

                // මුල තියෙන 'F' අකුර (index 0) අයින් කරලා, ඉලක්කම් ටික විතරක් අරන් 1ක් එකතු කරනවා
                int newIdNum = Integer.parseInt(lastId.substring(1)) + 1;

                // අලුත් ID එක Text Field එකට දානවා
                txtId.setText("F" + newIdNum); 
            } else {
                // Table එකේ මුකුත් නැත්නම් F1001 න් පටන් ගන්නවා
                txtId.setText("F1001"); 
            }
            conn.close();
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(null, e);
        }
    }

