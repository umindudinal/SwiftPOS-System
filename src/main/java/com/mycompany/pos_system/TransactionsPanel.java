    public void loadTransactions() {
        try {
            java.sql.Connection conn = DBConnect.connect();
            java.sql.Statement st = conn.createStatement();
            // අලුත්ම බිල උඩින්ම පේන්න ORDER BY පාවිච්චි කරනවා
            java.sql.ResultSet rs = st.executeQuery("SELECT * FROM sales ORDER BY sale_id DESC");

            javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) tblTransactions.getModel();
            model.setRowCount(0); 

            while(rs.next()) {
                // INV- අංකය හැදීම
                String invoiceNo = "INV-" + rs.getString("sale_id");

                // Payment method එක null නම් "Cash" කියලා පෙන්වන්න හදනවා (පරණ බිල් වලට)
                String payMethod = rs.getString("payment_method");
                if(payMethod == null) { payMethod = "Cash"; }

                model.addRow(new Object[]{
                    invoiceNo,
                    rs.getString("sale_date"), // Timestamp එක නිසා දිනය සහ වෙලාව දෙකම එනවා
                    rs.getString("net_total"),
                    payMethod,
                    rs.getString("balance")
                });
            }
            conn.close();
        } catch(Exception e) {
            javax.swing.JOptionPane.showMessageDialog(null, e);
        }
    }
    
    
