    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        try {
            String invoiceNo = lblInvoiceNo.getText();

            if(invoiceNo.isEmpty() || invoiceNo.equals("lblInvoiceNo")) {
                javax.swing.JOptionPane.showMessageDialog(null, "Please select a bill to print!");
                return;
            }

            StringBuilder bill = new StringBuilder();
            bill.append("==========================================\n");
            bill.append("             MY SUPERMARKET               \n");
            bill.append("        123 Main Street, Colombo 01       \n");
            bill.append("             Tel: 011-2345678             \n");
            bill.append("==========================================\n");
            bill.append(String.format("Invoice No: %-15s \n", invoiceNo));
            bill.append(String.format("Date & Time: %-15s \n", lblBillDate.getText()));
            bill.append(String.format("Pay Method: %-15s \n", lblPayMethod.getText()));
            bill.append("------------------------------------------\n");
            bill.append(String.format("%-15s %-5s %-8s %-8s\n", "Item Name", "Qty", "Price", "Total"));
            bill.append("------------------------------------------\n");

            // දකුණු පැත්තේ Table එකේ (tblBillItems) තියෙන බඩු ටික බිලට එකතු කරනවා
            for (int i = 0; i < tblBillItems.getRowCount(); i++) {
                String name = tblBillItems.getValueAt(i, 0).toString();
                String qty = tblBillItems.getValueAt(i, 1).toString();
                String price = tblBillItems.getValueAt(i, 2).toString();
                String tot = tblBillItems.getValueAt(i, 3).toString();

                if(name.length() > 14) { name = name.substring(0, 14) + "."; }
                bill.append(String.format("%-15s %-5s %-8s %-8s\n", name, qty, price, tot));
            }

            bill.append("------------------------------------------\n");
            bill.append(String.format("%-28s %12s\n", "Subtotal:", lblSubtotal.getText()));
            bill.append(String.format("%-28s %12s\n", "Discount:", lblDiscount.getText()));
            bill.append(String.format("%-28s %12s\n", "Total Amount:", lblBillTotal.getText()));
            bill.append("==========================================\n");
            bill.append("          Thank You, Come Again!          \n");
            bill.append("==========================================\n");

            javax.swing.JTextArea billArea = new javax.swing.JTextArea(bill.toString());
            billArea.setFont(new java.awt.Font("Monospaced", java.awt.Font.PLAIN, 14));
            billArea.setEditable(false);

            int printConfirm = javax.swing.JOptionPane.showConfirmDialog(null, new javax.swing.JScrollPane(billArea), "Print Receipt (Duplicate)", javax.swing.JOptionPane.YES_NO_OPTION);
            if (printConfirm == javax.swing.JOptionPane.YES_OPTION) {
                billArea.print(); 
            }

        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(null, e);
        }
    }//GEN-LAST:event_jButton2ActionPerformed


