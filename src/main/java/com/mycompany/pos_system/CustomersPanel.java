    public void loadCustomers() {
        try {
            java.sql.Connection conn = DBConnect.connect();
            java.sql.Statement st = conn.createStatement();
            java.sql.ResultSet rs = st.executeQuery("SELECT * FROM customers");

            javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) tblCustomers.getModel();
            model.setRowCount(0); 

            while(rs.next()) {
                model.addRow(new Object[]{
                    rs.getString("id"),
                    rs.getString("name"),
                    rs.getString("phone"),
                    rs.getString("email"),
                    rs.getString("address")
                });
            }
            conn.close();
        } catch(Exception e) {
            javax.swing.JOptionPane.showMessageDialog(null, e);
        }
    }
    
    public void autoId() {
        try {
            java.sql.Connection conn = DBConnect.connect();
            java.sql.Statement st = conn.createStatement();
            // Database එකේ තියෙන ලොකුම ID එක හොයාගන්නවා
            java.sql.ResultSet rs = st.executeQuery("SELECT MAX(id) FROM customers");

            if (rs.next() && rs.getString(1) != null) {
                int id = rs.getInt(1);
                txtId.setText(String.valueOf(id + 1)); // ඊළඟ අංකය පෙන්නනවා
            } else {
                txtId.setText("1"); // Table එක හිස් නම් 1 පෙන්නනවා
            }
            conn.close();
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(null, e);
        }
    }
    
