    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        try {
            String name = txtName.getText();
            String phone = txtPhone.getText();
            String email = txtEmail.getText();
            String address = txtAddress.getText();

            if (name.isEmpty() || phone.isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(null, "Name and Phone Number are required!");
                return;
            }

            java.sql.Connection conn = DBConnect.connect();
            String sql = "INSERT INTO customers (name, phone, email, address) VALUES (?, ?, ?, ?)";
            java.sql.PreparedStatement pst = conn.prepareStatement(sql);
            pst.setString(1, name);
            pst.setString(2, phone);
            pst.setString(3, email);
            pst.setString(4, address);

            pst.executeUpdate();
            conn.close();

            javax.swing.JOptionPane.showMessageDialog(null, "Customer Saved Successfully!");

            // කොටු ටික හිස් කරලා Table එක අලුත් කිරීම
            txtName.setText("");
            txtPhone.setText("");
            txtEmail.setText("");
            txtAddress.setText("");
            loadCustomers();
            autoId();

        } catch (java.sql.SQLIntegrityConstraintViolationException e) {
            javax.swing.JOptionPane.showMessageDialog(null, "This Phone Number already exists!");
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(null, e);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void tblCustomersMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblCustomersMouseClicked
        // TODO add your handling code here:
        try {
            int row = tblCustomers.getSelectedRow();
            String id = tblCustomers.getValueAt(row, 0).toString();

            java.sql.Connection conn = DBConnect.connect();
            java.sql.Statement st = conn.createStatement();
            java.sql.ResultSet rs = st.executeQuery("SELECT * FROM customers WHERE id = '" + id + "'");

            if(rs.next()) {
                txtId.setText(rs.getString("id"));
                txtName.setText(rs.getString("name"));
                txtPhone.setText(rs.getString("phone"));
                txtEmail.setText(rs.getString("email"));
                txtAddress.setText(rs.getString("address"));
            }
            conn.close();
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(null, e);
        }
    }//GEN-LAST:event_tblCustomersMouseClicked

