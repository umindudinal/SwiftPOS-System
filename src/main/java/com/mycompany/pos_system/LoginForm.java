    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
        // TODO add your handling code here:
        try {
            String un = txtUsername.getText();
            String pw = txtPassword.getText(); // PasswordField එකෙන් Password එක ගන්නවා

            // කොටු හිස්ද කියලා බලනවා
            if (un.isEmpty() || pw.isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(null, "Please enter both Username and Password!");
                return;
            }

            java.sql.Connection conn = DBConnect.connect();

            // Database එකේ මේ username සහ password එක තියෙන user කෙනෙක් ඉන්නවද කියලා බලනවා
            String sql = "SELECT * FROM users WHERE username = ? AND password = ?";
            java.sql.PreparedStatement pst = conn.prepareStatement(sql);
            pst.setString(1, un);
            pst.setString(2, pw);

            java.sql.ResultSet rs = pst.executeQuery();

            if (rs.next()) {
                // Login එක හරි නම්, Main Dashboard එක Open කරලා මේ Login Page එක වහනවා

                MainDashboard md = new MainDashboard();
                md.setVisible(true); // Dashboard එක පෙන්වනවා
                this.dispose();      // Login Window එක වහනවා

            } else {
                // පාස්වර්ඩ් වැරදි නම් Error එකක් දෙනවා
                javax.swing.JOptionPane.showMessageDialog(null, "Invalid Username or Password!", "Login Failed", javax.swing.JOptionPane.ERROR_MESSAGE);
            }

            conn.close();
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(null, e);
        }
    }//GEN-LAST:event_btnLoginActionPerformed

