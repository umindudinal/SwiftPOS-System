    public void loadDashboardData() {
        try {
            java.sql.Connection conn = DBConnect.connect();
            java.sql.Statement st = conn.createStatement();

            // 1. අද දවසේ මුළු ආදායම (Today's Sales)
            java.sql.ResultSet rs1 = st.executeQuery("SELECT SUM(net_total) FROM sales WHERE DATE(sale_date) = CURDATE()");
            if(rs1.next() && rs1.getString(1) != null) {
                lblTodaySales.setText("Rs. " + rs1.getString(1));
            } else {
                lblTodaySales.setText("Rs. 0.00");
            }

            // 2. අද දවසේ ගහපු බිල් ගණන (Total Orders)
            java.sql.ResultSet rs2 = st.executeQuery("SELECT COUNT(sale_id) FROM sales WHERE DATE(sale_date) = CURDATE()");
            if(rs2.next()) {
                lblTotalOrders.setText(rs2.getString(1));
            }

            // 3. සිස්ටම් එකේ තියෙන මුළු භාණ්ඩ වර්ග ගණන (Total Products)
            java.sql.ResultSet rs3 = st.executeQuery("SELECT COUNT(id) FROM products");
            if(rs3.next()) {
                lblTotalProducts.setText(rs3.getString(1));
            }

            // 4. Stock එක 10 ට වඩා අඩු භාණ්ඩ ගණන (Low Stock Items)
            java.sql.ResultSet rs4 = st.executeQuery("SELECT COUNT(id) FROM products WHERE quantity < 10");
            if(rs4.next()) {
                lblLowStock.setText(rs4.getString(1));
            }

            // 5. මෑතකදී ගහපු බිල් විස්තර Table එකට දැමීම
            java.sql.ResultSet rs5 = st.executeQuery("SELECT * FROM sales ORDER BY sale_id DESC LIMIT 10");
            javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) tblRecentSales.getModel();
            model.setRowCount(0); 

            while(rs5.next()) {
                model.addRow(new Object[]{
                    rs5.getString("sale_id"),
                    rs5.getString("sale_date"),
                    rs5.getString("subtotal"),
                    rs5.getString("discount"),
                    rs5.getString("net_total")
                });
            }

            conn.close();
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(null, e);
        }
    }

